-- Esquema inicial. Roda igual no PostgreSQL (produção) e no H2 em modo PostgreSQL (dev e testes).
-- Dinheiro em NUMERIC(14,2): até 999.999.999.999,99, sem erro de ponto flutuante.
-- Toda tabela com dado financeiro tem user_id. É assim que cada consulta filtra pelo dono.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Em minúsculas, para "Ana" e "ana" serem a mesma conta.
    username      VARCHAR(60)  NOT NULL,
    -- Hash com prefixo do algoritmo, por exemplo {bcrypt}$2a$10$...
    password_hash VARCHAR(255) NOT NULL,
    -- Hash do código de recuperação. O código em si nunca é guardado.
    recovery_hash VARCHAR(255),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE TABLE user_settings (
    user_id             BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    display_name        VARCHAR(60)   NOT NULL,
    preset_id           VARCHAR(20)   NOT NULL,
    reserve_months      INTEGER       NOT NULL CHECK (reserve_months BETWEEN 1 AND 60),
    reserve_base        VARCHAR(20)   NOT NULL,
    reserve_manual_cost NUMERIC(14,2) NOT NULL CHECK (reserve_manual_cost >= 0),
    -- Percentual do "Futuro" que vai para a reserva enquanto ela não estiver completa.
    reserve_priority    NUMERIC(5,2)  NOT NULL CHECK (reserve_priority BETWEEN 0 AND 100),
    sim_initial         NUMERIC(14,2) NOT NULL CHECK (sim_initial >= 0),
    sim_monthly         NUMERIC(14,2) NOT NULL CHECK (sim_monthly >= 0),
    sim_annual_rate     NUMERIC(7,4)  NOT NULL CHECK (sim_annual_rate BETWEEN 0 AND 100),
    sim_years           INTEGER       NOT NULL CHECK (sim_years BETWEEN 1 AND 50),
    sim_inflation       NUMERIC(7,4)  NOT NULL CHECK (sim_inflation BETWEEN 0 AND 100),
    sim_yearly_increase NUMERIC(7,4)  NOT NULL CHECK (sim_yearly_increase BETWEEN 0 AND 100),
    sim_target          NUMERIC(14,2) NOT NULL CHECK (sim_target >= 0),
    onboarded           BOOLEAN       NOT NULL
);

-- Potes da regra de distribuição da renda (ex.: Necessidades 50%).
CREATE TABLE buckets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    sort_order  INTEGER       NOT NULL,
    name        VARCHAR(60)   NOT NULL,
    percent     NUMERIC(5,2)  NOT NULL CHECK (percent BETWEEN 0 AND 100),
    kind        VARCHAR(20)   NOT NULL,
    description VARCHAR(500)
);
CREATE INDEX ix_buckets_user ON buckets (user_id, sort_order);

CREATE TABLE goals (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Identifica as metas padrão (reserva e carteira) sem depender de um id fixo.
    system_key      VARCHAR(30),
    name            VARCHAR(60)   NOT NULL,
    icon            VARCHAR(40)   NOT NULL,
    kind            VARCHAR(20)   NOT NULL,
    -- 0 = sem valor-alvo. Na reserva, o alvo é calculado.
    target          NUMERIC(14,2) NOT NULL CHECK (target >= 0),
    -- Primeiro dia do mês do prazo.
    deadline        DATE,
    initial_balance NUMERIC(14,2) NOT NULL CHECK (initial_balance >= 0),
    CONSTRAINT uq_goals_system_key UNIQUE (user_id, system_key)
);
CREATE INDEX ix_goals_user ON goals (user_id);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Categorias padrão (ex.: "other", que recebe lançamentos sem categoria).
    system_key VARCHAR(30),
    name       VARCHAR(60)   NOT NULL,
    icon       VARCHAR(40)   NOT NULL,
    bucket_id  BIGINT        NOT NULL REFERENCES buckets (id),
    kind       VARCHAR(20)   NOT NULL,
    -- Limite mensal opcional.
    budget     NUMERIC(14,2) CHECK (budget >= 0),
    -- Meta que recebe automaticamente os lançamentos desta categoria.
    goal_id    BIGINT REFERENCES goals (id) ON DELETE SET NULL,
    archived   BOOLEAN       NOT NULL,
    CONSTRAINT uq_categories_system_key UNIQUE (user_id, system_key)
);
CREATE INDEX ix_categories_user ON categories (user_id);
CREATE INDEX ix_categories_bucket ON categories (bucket_id);

-- Contas fixas e parcelamentos. Geram um lançamento por mês.
CREATE TABLE recurring_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(10)   NOT NULL,
    description  VARCHAR(200)  NOT NULL,
    amount       NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    category_id  BIGINT REFERENCES categories (id),
    goal_id      BIGINT REFERENCES goals (id) ON DELETE SET NULL,
    day_of_month INTEGER       NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    start_month  DATE          NOT NULL,
    -- Último mês, inclusive (parcelamentos).
    end_month    DATE,
    active       BOOLEAN       NOT NULL,
    CHECK (end_month IS NULL OR end_month >= start_month)
);
CREATE INDEX ix_recurring_user ON recurring_entries (user_id);

-- Meses em que o lançamento da conta fixa foi apagado à mão (não deve ser recriado).
CREATE TABLE recurring_skips (
    recurring_id  BIGINT NOT NULL REFERENCES recurring_entries (id) ON DELETE CASCADE,
    skipped_month DATE   NOT NULL,
    PRIMARY KEY (recurring_id, skipped_month)
);

CREATE TABLE transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type            VARCHAR(10)   NOT NULL,
    entry_date      DATE          NOT NULL,
    description     VARCHAR(200)  NOT NULL,
    amount          NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    category_id     BIGINT REFERENCES categories (id),
    goal_id         BIGINT REFERENCES goals (id) ON DELETE SET NULL,
    recurring_id    BIGINT REFERENCES recurring_entries (id) ON DELETE SET NULL,
    -- Mês da conta fixa a que este lançamento pertence. Impede gerar o mesmo mês duas vezes.
    recurring_month DATE,
    -- Pago (despesa) ou recebido (receita).
    paid            BOOLEAN       NOT NULL,
    CONSTRAINT uq_transactions_recurring_month UNIQUE (recurring_id, recurring_month)
);
-- Listagem paginada e resumo do mês: sempre por usuário e intervalo de datas.
CREATE INDEX ix_transactions_user_date ON transactions (user_id, entry_date DESC, id DESC);
CREATE INDEX ix_transactions_goal ON transactions (goal_id);
CREATE INDEX ix_transactions_category ON transactions (category_id);

-- Resultado do questionário de perfil. As respostas não são guardadas, só o resultado.
CREATE TABLE investor_profiles (
    user_id  BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    profile  VARCHAR(20) NOT NULL,
    score    INTEGER     NOT NULL CHECK (score >= 0),
    taken_on DATE        NOT NULL
);

-- Percentuais da carteira ajustados pelo usuário (sobrepõem os do perfil).
CREATE TABLE investor_profile_allocations (
    user_id     BIGINT       NOT NULL REFERENCES investor_profiles (user_id) ON DELETE CASCADE,
    asset_class VARCHAR(30)  NOT NULL,
    percent     NUMERIC(5,2) NOT NULL CHECK (percent BETWEEN 0 AND 100),
    PRIMARY KEY (user_id, asset_class)
);

-- Regras prontas de distribuição da renda. Os dados vêm na V2.
CREATE TABLE rule_presets (
    id          VARCHAR(20)  PRIMARY KEY,
    sort_order  INTEGER      NOT NULL,
    name        VARCHAR(60)  NOT NULL,
    short_name  VARCHAR(20)  NOT NULL,
    description VARCHAR(300) NOT NULL
);

CREATE TABLE rule_preset_buckets (
    preset_id          VARCHAR(20)  NOT NULL REFERENCES rule_presets (id) ON DELETE CASCADE,
    sort_order         INTEGER      NOT NULL,
    name               VARCHAR(60)  NOT NULL,
    percent            NUMERIC(5,2) NOT NULL CHECK (percent BETWEEN 0 AND 100),
    kind               VARCHAR(20)  NOT NULL,
    description        VARCHAR(500) NOT NULL,
    -- Categorias padrão que este pote "puxa" para si, separadas por vírgula (ex.: "goals,gifts").
    claimed_categories VARCHAR(200) NOT NULL,
    PRIMARY KEY (preset_id, sort_order)
);
